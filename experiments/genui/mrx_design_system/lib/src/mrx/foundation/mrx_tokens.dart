/// MRX's shared spacing, radius, and control measurements.
abstract final class MrxTokens {
  /// Extra-small spacing.
  static const space2xs = 4.0;

  /// Small spacing.
  static const spaceXs = 6.0;

  /// Compact spacing.
  static const spaceSm = 8.0;

  /// Default spacing between related content.
  static const spaceMd = 12.0;

  /// Comfortable spacing between groups.
  static const spaceLg = 16.0;

  /// Large section spacing.
  static const spaceXl = 24.0;

  /// Extra-large section spacing.
  static const space2xl = 32.0;

  /// Small control corner radius.
  static const radiusSm = 6.0;

  /// Default control corner radius.
  static const radiusMd = 8.0;

  /// Default card corner radius.
  static const radiusLg = 10.0;

  /// Prominent surface corner radius.
  static const radiusXl = 14.0;

  /// Standard compact-control height.
  static const controlHeight = 36.0;

  /// Minimum accessible touch target.
  static const touchTarget = 40.0;
}
